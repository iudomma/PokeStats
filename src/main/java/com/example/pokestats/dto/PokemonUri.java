package com.example.pokestats.dto;

import lombok.Builder;
import lombok.Data;

@Data
@Builder
public class PokemonUri {

	private String name;
	private String url;

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}

	public String getUrl() {
		return url;
	}

	public void setUrl(String url) {
		this.url = url;
	}

}
